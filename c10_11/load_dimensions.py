def _postgres_engine(database: str, prefix: str) -> Engine:
    return sa.create_engine(
        URL.create(
            "postgresql+psycopg2",
            username=os.getenv(f"{prefix}_USER", os.getenv("PG_USER", "postgres")),
            password=os.getenv(f"{prefix}_PASSWORD", os.getenv("PG_PASSWORD")),
            host=os.getenv(f"{prefix}_HOST", os.getenv("PG_HOST", "127.0.0.1")),
            port=int(os.getenv(f"{prefix}_PORT", os.getenv("PG_PORT", "5432"))),
            database=database,
        )
    )


def _sql_server_jdbc() -> tuple[str, dict[str, str]]:
    host = os.getenv("SQL_SERVER_INSTANCE", "localhost")
    port = os.getenv("SQL_SERVER_PORT", "1433")
    url = os.getenv(
        "SQLSERVER_JDBC_URL",
        f"jdbc:sqlserver://{host}:{port};databaseName={SQL_SERVER_DATABASE};"
        "encrypt=true;trustServerCertificate=true",
    )
    properties = {"driver": "com.microsoft.sqlserver.jdbc.SQLServerDriver"}
    username = os.getenv("SQL_SERVER_USER")
    password = os.getenv("SQL_SERVER_PASSWORD")
    if username:
        properties.update({"user": username, "password": password or ""})
    else:
        properties["integratedSecurity"] = "true"
    return url, properties


def _postgres_jdbc(prefix: str, database: str) -> tuple[str, dict[str, str]]:
    host = os.getenv(f"{prefix}_HOST", os.getenv("PG_HOST", "127.0.0.1"))
    port = os.getenv(f"{prefix}_PORT", os.getenv("PG_PORT", "5432"))
    url = os.getenv(
        f"{prefix}_JDBC_URL",
        f"jdbc:postgresql://{host}:{port}/{database}",
    )
    properties = {"driver": "org.postgresql.Driver"}
    username = os.getenv(f"{prefix}_USER", os.getenv("PG_USER", "postgres"))
    password = os.getenv(f"{prefix}_PASSWORD", os.getenv("PG_PASSWORD"))
    if username:
        properties["user"] = username
    if password:
        properties["password"] = password
    return url, properties


def _ensure_dw_database() -> None:
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", DW_DATABASE):
        raise ValueError("DW_DATABASE must contain only letters, digits, or underscores.")
    engine = _postgres_engine(DW_ADMIN_DATABASE, "DW")
    try:
        with engine.connect().execution_options(isolation_level="AUTOCOMMIT") as conn:
            exists = conn.execute(
                text("SELECT 1 FROM pg_database WHERE datname = :name"),
                {"name": DW_DATABASE},
            ).scalar()
            if not exists:
                conn.exec_driver_sql(f'CREATE DATABASE "{DW_DATABASE}"')
    finally:
        engine.dispose()


def _create_spark() -> SparkSession:
    builder = (
        SparkSession.builder
        .appName("WinCommerce-DIM-ETL")
        .master(os.getenv("SPARK_MASTER", "local[*]"))
        .config("spark.ui.enabled", "false")
        .config("spark.sql.session.timeZone", "UTC")
    )
    jdbc_jars = os.getenv("SPARK_JDBC_JARS")
    if jdbc_jars:
        builder = builder.config("spark.jars", jdbc_jars)
    spark = builder.getOrCreate()
    spark.sparkContext.setLogLevel("WARN")
    return spark


def _read_jdbc(
    spark: SparkSession,
    url: str,
    query: str,
    properties: dict[str, str],
) -> DataFrame:
    return (
        spark.read.format("jdbc")
        .option("url", url)
        .option("dbtable", f"({query}) AS source_query")
        .options(**properties)
        .load()
    )


def _extract_sources(spark: SparkSession) -> dict[str, DataFrame]:
    sql_url, sql_properties = _sql_server_jdbc()
    pg_url, pg_properties = _postgres_jdbc("SOURCE_PG", SOURCE_PG_DATABASE)

    queries = {
        "stores": (
            sql_url,
            """
            SELECT CAST(s.store_id AS VARCHAR(50)) AS store_id,
                   s.store_name, s.store_type,
                   CAST(s.region_id AS VARCHAR(50)) AS region_id,
                   r.region_name, s.province, s.district, s.status
            FROM stores s
            LEFT JOIN regions r ON r.region_id = s.region_id
            """,
            sql_properties,
        ),
        "products": (
            sql_url,
            """
            SELECT CAST(p.product_id AS VARCHAR(50)) AS product_id,
                   p.product_name, p.brand,
                   CAST(p.category_id AS VARCHAR(50)) AS category_id,
                   c.category_name, p.unit, p.status, p.shelf_life_days
            FROM products p
            LEFT JOIN categories c ON c.category_id = p.category_id
            """,
            sql_properties,
        ),
        "customers": (
            sql_url,
            """
            SELECT CAST(customer_id AS VARCHAR(50)) AS customer_id,
                   full_name AS customer_name, gender, date_of_birth,
                   member_tier AS member_level, join_date AS registration_date,
                   registration_channel, status
            FROM customers
            """,
            sql_properties,
        ),
        "promotions": (
            sql_url,
            """
            SELECT CAST(promotion_id AS VARCHAR(50)) AS promotion_id,
                   promotion_name, promotion_type,
                   CAST(start_datetime AS DATE) AS start_date,
                   CAST(end_datetime AS DATE) AS end_date,
                   status AS promotion_status
            FROM promotions
            """,
            sql_properties,
        ),
        "promotion_products": (
            sql_url,
            """
            SELECT CAST(promotion_id AS VARCHAR(50)) AS promotion_id,
                   CAST(product_id AS VARCHAR(50)) AS product_id
            FROM promotion_products
            """,
            sql_properties,
        ),
        "warehouses": (
            pg_url,
            """
            SELECT CAST(warehouse_id AS VARCHAR(50)) AS warehouse_id,
                   warehouse_name, address, province, status
            FROM warehouses
            """,
            pg_properties,
        ),
        "suppliers": (
            pg_url,
            """
            SELECT CAST(supplier_id AS VARCHAR(50)) AS supplier_id,
                   supplier_name, phone, email, address, status
            FROM suppliers
            """,
            pg_properties,
        ),
        "supplier_products": (
            pg_url,
            """
            SELECT CAST(supplier_id AS VARCHAR(50)) AS supplier_id,
                   CAST(product_id AS VARCHAR(50)) AS product_id,
                   supplier_product_code, unit_cost, lead_time_days, status
            FROM supplier_products
            """,
            pg_properties,
        ),
        "goods_receipt_items": (
            pg_url,
            """
            SELECT batch_no, CAST(product_id AS VARCHAR(50)) AS product_id, expiry_date
            FROM goods_receipt_items
            """,
            pg_properties,
        ),
    }

    data = {}
    for name, (url, query, properties) in queries.items():
        data[name] = _read_jdbc(spark, url, query, properties)
        print(f"[Extract] Spark DataFrame ready: {name}")
    return data


def _source_date_bounds(spark: SparkSession) -> tuple[date, date]:
    sql_url, sql_properties = _sql_server_jdbc()
    pg_url, pg_properties = _postgres_jdbc("SOURCE_PG", SOURCE_PG_DATABASE)

    sql_dates = _read_jdbc(
        spark,
        sql_url,
        """
        SELECT CAST(order_datetime AS DATE) AS source_date FROM sales_orders
        UNION ALL SELECT CAST(open_date AS DATE) FROM stores
        UNION ALL SELECT CAST(join_date AS DATE) FROM customers
        UNION ALL SELECT CAST(start_datetime AS DATE) FROM promotions
        UNION ALL SELECT CAST(end_datetime AS DATE) FROM promotions
        """,
        sql_properties,
    )
    pg_dates = _read_jdbc(
        spark,
        pg_url,
        """
        SELECT CAST(receipt_datetime AS DATE) AS source_date FROM goods_receipts
        UNION ALL SELECT CAST(order_date AS DATE) FROM purchase_orders
        UNION ALL SELECT expected_delivery_date FROM purchase_orders
        UNION ALL SELECT CAST(count_date AS DATE) FROM inventory_counts
        UNION ALL SELECT CAST(last_updated AS DATE) FROM inventory_balance
        UNION ALL SELECT expiry_date FROM goods_receipt_items
        """,
        pg_properties,
    )
    bounds = (
        sql_dates.unionByName(pg_dates)
        .agg(F.min("source_date").alias("min_date"), F.max("source_date").alias("max_date"))
        .first()
    )
    if bounds["min_date"] is None or bounds["max_date"] is None:
        raise ValueError("No dates were found in source databases; cannot build DIM_DATE.")
    return bounds["min_date"], bounds["max_date"]


def _clean_text(df: DataFrame, columns: tuple[str, ...]) -> DataFrame:
    for column in columns:
        value = F.trim(F.col(column).cast("string"))
        df = df.withColumn(column, F.when(F.length(value) > 0, value))
    return df


def _assert_unique_natural_key(
    df: DataFrame, keys: tuple[str, ...], dimension_name: str
) -> None:
    duplicates = (
        df.groupBy(*keys).count().filter(F.col("count") > 1).limit(5).collect()
    )
    if duplicates:
        raise ValueError(f"{dimension_name} contains duplicate natural keys: {duplicates}")


def _assert_references_exist(
    child: DataFrame,
    child_key: str,
    parent: DataFrame,
    parent_key: str,
    description: str,
) -> None:
    missing = (
        child.select(F.col(child_key).alias("_child_key"))
        .filter(F.col("_child_key").isNotNull())
        .distinct()
        .join(
            parent.select(F.col(parent_key).alias("_parent_key")).distinct(),
            F.col("_child_key") == F.col("_parent_key"),
            "left_anti",
        )
        .limit(5)
        .collect()
    )
    if missing:
        raise ValueError(f"{description} has unresolved source keys: {missing}")


def _holiday_dates(start_year: int, end_year: int) -> list[str]:
    dates = [
        date(year, month, day).isoformat()
        for year in range(start_year, end_year + 1)
        for month, day in FIXED_VIETNAM_HOLIDAYS
    ]
    for value in filter(None, (part.strip() for part in os.getenv("VIETNAM_HOLIDAYS", "").split(","))):
        try:
            dates.append(date.fromisoformat(value).isoformat())
        except ValueError as exc:
            raise ValueError(
                f"Invalid VIETNAM_HOLIDAYS value {value!r}; expected YYYY-MM-DD."
            ) from exc
    return list(set(dates))


def _make_dim_date(spark: SparkSession, bounds: tuple[date, date]) -> DataFrame:
    start_date, end_date = bounds
    dates = (
        spark.range(1)
        .select(
            F.explode(
                F.sequence(
                    F.to_date(F.lit(start_date.isoformat())),
                    F.to_date(F.lit(end_date.isoformat())),
                    F.expr("INTERVAL 1 DAY"),
                )
            ).alias("full_date")
        )
        .withColumn("date_dim_id", F.date_format("full_date", "yy/MM/dd"))
        .withColumn("day", F.dayofmonth("full_date"))
        .withColumn("day_of_week", F.dayofweek("full_date"))
        .withColumn("week", F.weekofyear("full_date"))
        .withColumn("month", F.month("full_date"))
        .withColumn("quarter", F.quarter("full_date"))
        .withColumn("year", F.year("full_date"))
        .withColumn("is_weekend", F.dayofweek("full_date").isin(1, 7))
        .withColumn(
            "is_holiday",
            F.col("full_date").cast("string").isin(
                _holiday_dates(start_date.year, end_date.year)
            ),
        )
        .select(*DIM_COLUMNS["dim_date"])
    )
    return dates


def _make_dim_time(spark: SparkSession) -> DataFrame:
    time_values = (
        spark.range(24 * 60)
        .withColumn("hour", (F.col("id") / 60).cast("int"))
        .withColumn("minute", (F.col("id") % 60).cast("int"))
        .withColumn("time_label", F.format_string("%02d:%02d", "hour", "minute"))
        .withColumn("time_dim_id", F.col("time_label"))
        .withColumn(
            "time_period",
            F.when(F.col("hour").between(5, 11), "Morning")
            .when(F.col("hour").between(12, 16), "Afternoon")
            .when(F.col("hour").between(17, 20), "Evening")
            .otherwise("Night"),
        )
        .withColumn(
            "is_peak_hour",
            F.col("hour").between(7, 9) | F.col("hour").between(17, 19),
        )
        .select(*DIM_COLUMNS["dim_time"])
    )
    return time_values


def _transform_dimensions(
    spark: SparkSession,
    source: dict[str, DataFrame],
    date_bounds: tuple[date, date],
) -> dict[str, DataFrame]:
    # 1. DIM_DATE and DIM_TIME are generated as Spark DataFrames.
    dim_date = _make_dim_date(spark, date_bounds)
    dim_time = _make_dim_time(spark)

    # 2. Join and clean source tables using PySpark DataFrame operations.
    stores = _clean_text(
        source["stores"],
        (
            "store_id", "store_name", "store_type", "region_id", "region_name",
            "province", "district", "status",
        ),
    ).filter(F.col("store_id").isNotNull()).select(*DIM_COLUMNS["dim_store"])

    warehouses = _clean_text(
        source["warehouses"], ("warehouse_id", "warehouse_name", "address", "province", "status")
    ).filter(F.col("warehouse_id").isNotNull()).withColumn(
        "warehouse_type", F.lit(None).cast("string")
    ).select(*DIM_COLUMNS["dim_warehouse"])

    products = _clean_text(
        source["products"],
        (
            "product_id", "product_name", "brand", "category_id",
            "category_name", "unit", "status",
        ),
    ).filter(F.col("product_id").isNotNull())

    customers = _clean_text(
        source["customers"],
        (
            "customer_id", "customer_name", "gender", "member_level",
            "registration_channel", "status",
        ),
    ).filter(F.col("customer_id").isNotNull())

    promotions = _clean_text(
        source["promotions"],
        ("promotion_id", "promotion_name", "promotion_type", "promotion_status"),
    ).filter(F.col("promotion_id").isNotNull())

    suppliers = _clean_text(
        source["suppliers"],
        ("supplier_id", "supplier_name", "phone", "email", "address", "status"),
    ).filter(F.col("supplier_id").isNotNull()).withColumn(
        "contact_name", F.lit(None).cast("string")
    )

    # The PostgreSQL product IDs refer to SQL Server products; retain one DW
    # product identity and fail clearly if the source systems do not align.
    supplier_products = _clean_text(
        source["supplier_products"], ("supplier_id", "product_id")
    )
    _assert_references_exist(
        supplier_products, "product_id", products, "product_id",
        "supplier_products to multichannel_sales.products",
    )
    _assert_references_exist(
        supplier_products, "supplier_id", suppliers, "supplier_id",
        "supplier_products to suppliers",
    )

    promotion_products = _clean_text(
        source["promotion_products"], ("promotion_id", "product_id")
    )
    _assert_references_exist(
        promotion_products, "promotion_id", promotions, "promotion_id",
        "promotion_products to promotions",
    )
    _assert_references_exist(
        promotion_products, "product_id", products, "product_id",
        "promotion_products to products",
    )

    batch_products = products.select("product_id", "shelf_life_days")
    batches = (
        _clean_text(source["goods_receipt_items"], ("batch_no", "product_id"))
        .filter(F.col("batch_no").isNotNull() & F.col("product_id").isNotNull())
        .join(batch_products, on="product_id", how="left")
        .withColumn(
            "manufacture_date",
            F.when(
                F.col("expiry_date").isNotNull() & (F.col("shelf_life_days") >= 0),
                F.date_sub(F.col("expiry_date"), F.col("shelf_life_days")),
            ).cast("date"),
        )
        .withColumn(
            "expiry_status",
            F.when(F.col("expiry_date").isNull(), "UNKNOWN")
            .when(F.col("expiry_date") < F.current_date(), "EXPIRED")
            .when(
                F.col("expiry_date") <= F.date_add(F.current_date(), NEAR_EXPIRY_DAYS),
                "NEAR_EXPIRY",
            )
            .otherwise("VALID"),
        )
        .select(*DIM_COLUMNS["dim_batch"])
        .dropDuplicates(["product_id", "batch_no"])
    )

    dimensions = {
        "dim_date": dim_date,
        "dim_time": dim_time,
        "dim_store": stores,
        "dim_warehouse": warehouses,
        "dim_product": products.select(*DIM_COLUMNS["dim_product"]),
        "dim_customer": customers.select(*DIM_COLUMNS["dim_customer"]),
        "dim_promotion": promotions.select(*DIM_COLUMNS["dim_promotion"]),
        "dim_supplier": suppliers.select(*DIM_COLUMNS["dim_supplier"]),
        "dim_batch": batches,
    }
    natural_keys = {
        "dim_date": ("date_dim_id",),
        "dim_time": ("time_dim_id",),
        "dim_store": ("store_id",),
        "dim_warehouse": ("warehouse_id",),
        "dim_product": ("product_id",),
        "dim_customer": ("customer_id",),
        "dim_promotion": ("promotion_id",),
        "dim_supplier": ("supplier_id",),
        "dim_batch": ("product_id", "batch_no"),
    }
    for name, keys in natural_keys.items():
        _assert_unique_natural_key(dimensions[name], keys, name.upper())
    return dimensions


def _create_dw_objects(conn: sa.Connection) -> None:
    for schema in (STAGING_SCHEMA, DW_SCHEMA, ETL_LOG_SCHEMA):
        conn.exec_driver_sql(f'CREATE SCHEMA IF NOT EXISTS "{schema}"')
    for ddl in DIMENSION_DDL:
        conn.exec_driver_sql(ddl)

    # Staging columns match the Spark DataFrame payload; identity surrogate keys
    # are generated only in the final DW dimension tables.
    for name, columns in DIM_COLUMNS.items():
        column_list = ", ".join(f'"{column}"' for column in columns)
        conn.exec_driver_sql(
            f"""
            CREATE TABLE IF NOT EXISTS "{STAGING_SCHEMA}"."stg_{name}" AS
            SELECT {column_list}
            FROM "{DW_SCHEMA}"."{name}"
            WHERE FALSE
            """
        )
    conn.exec_driver_sql(
        """
        CREATE TABLE IF NOT EXISTS etl_log.etl_run_log (
            run_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            process_name VARCHAR(100) NOT NULL,
            started_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
            completed_at TIMESTAMP,
            status VARCHAR(20) NOT NULL,
            rows_processed JSONB,
            error_message TEXT
        )
        """
    )


def _jdbc_write_properties() -> dict[str, str]:
    url, properties = _postgres_jdbc("DW", DW_DATABASE)
    return {"url": url, **properties}


def _load_dimensions(dimensions: dict[str, DataFrame]) -> dict[str, int]:
    jdbc_properties = _jdbc_write_properties()
    loaded: dict[str, int] = {}
    for name, dataframe in dimensions.items():
        staging_table = f"{STAGING_SCHEMA}.stg_{name}"
        dataframe.write.jdbc(
            table=staging_table,
            mode="overwrite",
            properties=jdbc_properties,
        )
        # Spark writes the staging table. PostgreSQL performs the idempotent
        # natural-key upsert and lets identity columns allocate surrogate keys.
        columns = DIM_COLUMNS[name]
        column_list = ", ".join(f'"{column}"' for column in columns)
        conflict_columns = (
            '"product_id", "batch_no"' if name == "dim_batch"
            else f'"{columns[0]}"'
        )
        update_columns = [column for column in columns if f'"{column}"' not in conflict_columns]
        update_clause = ", ".join(
            f'"{column}" = EXCLUDED."{column}"' for column in update_columns
        )
        merge_sql = f"""
            INSERT INTO "{DW_SCHEMA}"."{name}" ({column_list})
            SELECT {column_list}
            FROM "{STAGING_SCHEMA}"."stg_{name}"
            ON CONFLICT ({conflict_columns})
            DO UPDATE SET {update_clause}
        """
        engine = _postgres_engine(DW_DATABASE, "DW")
        try:
            with engine.begin() as conn:
                conn.exec_driver_sql(merge_sql)
                loaded[name] = conn.execute(
                    text(f'SELECT COUNT(*) FROM "{STAGING_SCHEMA}"."stg_{name}"')
                ).scalar_one()
        finally:
            engine.dispose()
        print(f"[Load] dw.{name}: {loaded[name]:,} source rows")
    return loaded


def _validate_counts(engine: Engine) -> dict[str, int]:
    with engine.connect() as conn:
        return {
            name: conn.execute(
                text(f'SELECT COUNT(*) FROM "{DW_SCHEMA}"."{name}"')
            ).scalar_one()
            for name in DIM_COLUMNS
        }


def run_etl() -> None:
    if not DW_DATABASE:
        raise ValueError("DW_DATABASE cannot be empty.")

    _ensure_dw_database()
    target = _postgres_engine(DW_DATABASE, "DW")
    spark: SparkSession | None = None
    run_id: int | None = None

    try:
        with target.begin() as conn:
            _create_dw_objects(conn)
            run_id = conn.execute(
                text(
                    """
                    INSERT INTO etl_log.etl_run_log (process_name, status)
                    VALUES ('load_dimensions', 'RUNNING')
                    RETURNING run_id
                    """
                )
            ).scalar_one()

        spark = _create_spark()
        print("[Extract] Reading SQL Server and PostgreSQL sources with Spark JDBC.")
        source = _extract_sources(spark)
        date_bounds = _source_date_bounds(spark)
        print(f"[DIM_DATE] Generating dates from {date_bounds[0]} through {date_bounds[1]}.")

        dimensions = _transform_dimensions(spark, source, date_bounds)
        loaded = _load_dimensions(dimensions)
        final_counts = _validate_counts(target)

        with target.begin() as conn:
            conn.execute(
                text(
                    """
                    UPDATE etl_log.etl_run_log
                    SET completed_at = CURRENT_TIMESTAMP,
                        status = 'SUCCESS',
                        rows_processed = CAST(:counts AS JSONB)
                    WHERE run_id = :run_id
                    """
                ),
                {"counts": json.dumps(loaded), "run_id": run_id},
            )

        print("\n[Validate] Total rows currently in Data Warehouse:")
        for name, count in final_counts.items():
            print(f"  dw.{name}: {count:,}")
    except Exception as exc:
        if run_id is not None:
            with target.begin() as conn:
                conn.execute(
                    text(
                        """
                        UPDATE etl_log.etl_run_log
                        SET completed_at = CURRENT_TIMESTAMP,
                            status = 'FAILED',
                            error_message = :message
                        WHERE run_id = :run_id
                        """
                    ),
                    {"message": str(exc)[:4000], "run_id": run_id},
                )
        raise
    finally:
        if spark is not None:
            spark.stop()
        target.dispose()


if __name__ == "__main__":
    run_etl()
