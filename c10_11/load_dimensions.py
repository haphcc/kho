def extract_and_load_staging(sql_eng: Engine, pg_src_eng: Engine, dw_eng: Engine) -> dict[str, int]:
    """
    Trích xuất dữ liệu từ SQL Server và PostgreSQL nguồn,
    lưu trực tiếp vào các bảng staging tương ứng thuộc schema staging trong wincommerce_dw.
    """
    print("\n" + "=" * 78)
    print(">>> BƯỚC 1 & 2: EXTRACT NGUỒN VÀ NẠP VÀO SCHEMA [STAGING] TRONG WINCOMMERCE_DW")
    print("=" * 78)
    
    stg_counts = {}

    # 1. Trích xuất từ SQL Server (multichannel_sales)
    sql_queries = {
        "stg_stores": "SELECT store_id, region_id, store_code, store_name, store_type, address, district, province, open_date, close_date, floor_area, status FROM stores",
        "stg_regions": "SELECT region_id, region_code, region_name, status FROM regions",
        "stg_products": "SELECT product_id, category_id, sku, product_name, brand, unit, list_price, standard_cost, vat_rate, shelf_life_days, is_fresh, status FROM products",
        "stg_categories": "SELECT category_id, parent_category_id, category_name, category_level, status FROM categories",
        "stg_customers": "SELECT customer_id, full_name, gender, date_of_birth, phone, email, province, registration_channel, join_date, member_tier, loyalty_points, status FROM customers",
        "stg_promotions": "SELECT promotion_id, promotion_name, promotion_type, discount_value, start_datetime, end_datetime, min_order_value, status FROM promotions",
        "stg_promotion_products": "SELECT promotion_id, product_id FROM promotion_products",
    }

    print(" [Extract] Đang đọc dữ liệu từ SQL Server [multichannel_sales]...")
    with sql_eng.connect() as conn:
        for tbl_name, qry in sql_queries.items():
            df = pd.read_sql(qry, conn)
            # Nạp vào schema staging của wincommerce_dw
            df.to_sql(tbl_name, dw_eng, schema=STAGING_SCHEMA, if_exists="replace", index=False)
            stg_counts[tbl_name] = len(df)
            print(f"   -> [SQL Server] -> staging.{tbl_name:<22}: {len(df):>5} dòng")

    # 2. Trích xuất từ PostgreSQL (logistics_purchasing)
    pg_queries = {
        "stg_warehouses": "SELECT warehouse_id, warehouse_code, warehouse_name, address, province, region, status FROM warehouses",
        "stg_suppliers": "SELECT supplier_id, supplier_code, supplier_name, phone, email, address, province, status FROM suppliers",
        "stg_supplier_products": "SELECT supplier_id, product_id, supplier_product_code, unit_cost, lead_time_days, min_order_qty, status FROM supplier_products",
        "stg_goods_receipts": "SELECT receipt_id, purchase_order_id, warehouse_id, receipt_number, receipt_datetime, status FROM goods_receipts",
        "stg_goods_receipt_items": "SELECT receipt_item_id, receipt_id, po_item_id, product_id, batch_no, expiry_date, received_qty, accepted_qty, rejected_qty, unit_cost FROM goods_receipt_items",
    }

    print("\n [Extract] Đang đọc dữ liệu từ PostgreSQL [logistics_purchasing]...")
    with pg_src_eng.connect() as conn:
        for tbl_name, qry in pg_queries.items():
            df = pd.read_sql(qry, conn)
            df.to_sql(tbl_name, dw_eng, schema=STAGING_SCHEMA, if_exists="replace", index=False)
            stg_counts[tbl_name] = len(df)
            print(f"   -> [PostgreSQL] -> staging.{tbl_name:<22}: {len(df):>5} dòng")

    return stg_counts


