def validate_dw_dimensions(dw_eng: Engine) -> None:
    print("\n" + "=" * 78)
    print(">>> BƯỚC 5: KIỂM TRA CHẤT LƯỢNG & ĐỐI SOÁT DỮ LIỆU DATA WAREHOUSE")
    print("=" * 78)

    tables_to_check = [
        ("dw.dim_date", "date_dim_id", "date_dim_id"),
        ("dw.dim_time", "time_dim_id", "time_dim_id"),
        ("dw.dim_store", "store_dim_id", "store_id"),
        ("dw.dim_warehouse", "warehouse_dim_id", "warehouse_id"),
        ("dw.dim_product", "product_dim_id", "product_id"),
        ("dw.dim_customer", "customer_dim_id", "customer_id"),
        ("dw.dim_promotion", "promotion_dim_id", "promotion_id"),
        ("dw.dim_supplier", "supplier_dim_id", "supplier_id"),
        ("dw.dim_batch", "batch_dim_id", "product_id, batch_no"),
    ]

    print(f"{'Tên Bảng DIM':<20} | {'Tổng dòng':>10} | {'Surrogate Key Dup':>18} | {'Trạng thái':<12}")
    print("-" * 70)

    with dw_eng.connect() as conn:
        for tbl, sk, nk in tables_to_check:
            cnt = conn.execute(text(f"SELECT COUNT(*) FROM {tbl}")).scalar()
            sk_dup = conn.execute(
                text(f"SELECT COUNT(*) FROM (SELECT {sk} FROM {tbl} GROUP BY {sk} HAVING COUNT(*) > 1) t")
            ).scalar()

            status = "CHÍNH XÁC (OK)" if cnt > 0 and sk_dup == 0 else "CẦN KIỂM TRA"
            print(f"{tbl:<20} | {cnt:>10,} | {sk_dup:>18} | {status:<12}")

    print("=" * 78)


def run_etl() -> None:
    print("*" * 78)
    print("  KHỞI ĐỘNG TIẾN TRÌNH ETL CÂU 10: NẠP 9 BẢNG DIMENSION (WINCOMMERCE DW)")
    print("*" * 78)

    ensure_dw_database()
    dw_eng = get_postgres_engine(DW_DATABASE)
    create_dw_schemas_and_tables(dw_eng)

    run_id = None
    with dw_eng.begin() as conn:
        run_id = conn.execute(
            text(
                """
                INSERT INTO etl_log.etl_run_log (process_name, status)
                VALUES ('load_dimensions', 'RUNNING')
                RETURNING run_id
                """
            )
        ).scalar()

    try:
        sql_eng = get_sql_server_engine(SQL_SERVER_DATABASE)
        pg_src_eng = get_postgres_engine(SOURCE_PG_DATABASE)

        stg_counts = extract_and_load_staging(sql_eng, pg_src_eng, dw_eng)
        dim_counts = transform_and_load_dimensions(dw_eng)
        validate_dw_dimensions(dw_eng)

        all_metrics = {"staging_counts": stg_counts, "dimension_counts": dim_counts}
        with dw_eng.begin() as conn:
            conn.execute(
                text(
                    """
                    UPDATE etl_log.etl_run_log
                    SET completed_at = CURRENT_TIMESTAMP,
                        status = 'SUCCESS',
                        rows_processed = CAST(:metrics AS JSONB)
                    WHERE run_id = :run_id
                    """
                ),
                {"metrics": json.dumps(all_metrics, ensure_ascii=False), "run_id": run_id},
            )

        print("\n [HOÀN TẤT] Quá trình ETL nạp 9 bảng DIM cho wincommerce_dw THÀNH CÔNG!")
        print(f"   -> Nhật ký được lưu tại etl_log.etl_run_log với RUN_ID = {run_id}")

    except Exception as exc:
        print(f"\n❌ [LỖI ETL] {exc}")
        if run_id is not None:
            with dw_eng.begin() as conn:
                conn.execute(
                    text(
                        """
                        UPDATE etl_log.etl_run_log
                        SET completed_at = CURRENT_TIMESTAMP,
                            status = 'FAILED',
                            error_message = :err
                        WHERE run_id = :run_id
                        """
                    ),
                    {"err": str(exc)[:4000], "run_id": run_id},
                )
        raise
    finally:
        dw_eng.dispose()


if __name__ == "__main__":
    run_etl()
